// `doctor`'s checks for the enforcement pin (doc/plan-pin-enforcement-binary.md
// D5). The generated hooks and the `gh` shim run the CLI by the absolute path
// pinned at install time; these checks say whether that holds on this machine.
//
//   ENFORCEMENT_UNPINNED (fail)       an installed hook, the shim or a Claude Code hook command still calls
//                                     `repo-aegis` by name: whatever is first on
//                                     PATH decides what enforces, and a missing one
//                                     switches enforcement off (an older install).
//   ENFORCEMENT_PIN_MISSING (fail)    a pinned node or CLI path no longer exists, so
//                                     the script refuses until it is re-pinned.
//   MULTIPLE_INSTALLS (warn)          more than one `repo-aegis` is reachable on PATH,
//                                     or the first one is not the pinned one: the
//                                     person's terminal and the hooks run different code.
//
// Pure readers. Nothing found on PATH is executed: a version comes from the
// package.json next to the entry file, never from running it.
import { accessSync, constants, readFileSync, realpathSync, statSync } from "node:fs";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parsePinFromScript, repoAegisHome, type EnforcementPin } from "@de-otio/repo-aegis-core";
import { currentEnforcementPin } from "../enforcement-pin.js";
import type { DoctorCheck } from "./doctor-checks.js";
import { unpinnedClaudeHooks } from "./install-claude-md.js";
import { SHIM_HEADER_LINE } from "./shim-script.js";

/** First comment line the generated hooks carry (see `core/src/hook-scripts.ts`). */
const HOOK_HEADER_FRAGMENT = "Generated by `repo-aegis install hooks`";

type Installer = "hooks" | "shim" | "claude-md";

interface InstalledScript {
  label: string;
  installer: Installer;
  /** The pin rendered into it, or null for an old script that calls repo-aegis by name. */
  pin: EnforcementPin | null;
}

function readText(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

/** The scripts `install hooks` and `install shim` wrote under `home`, as they are on disk now. */
function installedScripts(home: string): InstalledScript[] {
  const out: InstalledScript[] = [];
  for (const name of ["pre-commit", "pre-push"]) {
    const text = readText(join(home, "hooks", name));
    if (text !== null && text.includes(HOOK_HEADER_FRAGMENT)) {
      out.push({ label: `${name} hook`, installer: "hooks", pin: parsePinFromScript(text) });
    }
  }
  const shim = readText(join(home, "bin", "gh"));
  if (shim !== null && shim.includes(SHIM_HEADER_LINE)) {
    out.push({ label: "gh shim", installer: "shim", pin: parsePinFromScript(shim) });
  }
  return out;
}

/** The command that re-pins the given installers. */
function fixFor(installers: Iterable<Installer>): string {
  const set = new Set(installers);
  return [...(["hooks", "shim", "claude-md"] as const)]
    .filter(i => set.has(i))
    .map(i => `repo-aegis install ${i}`)
    .join(" && ");
}

function unpinnedCheck(scripts: InstalledScript[], claudeHooks: string[]): DoctorCheck {
  const unpinned = scripts.filter(s => s.pin === null);
  if (unpinned.length === 0 && claudeHooks.length === 0) {
    return { code: "ENFORCEMENT_UNPINNED", ok: true, detail: "no installed hook or shim calls repo-aegis by name" };
  }
  const what = [
    ...unpinned.map(s => `the ${s.label}`),
    ...(claudeHooks.length > 0 ? [`the Claude Code hook(s) ${claudeHooks.join(", ")}`] : []),
  ];
  return {
    code: "ENFORCEMENT_UNPINNED",
    ok: false,
    detail:
      `${what.join(", ")} call(s) repo-aegis by name, so a repo-aegis or node that comes first on PATH ` +
      "decides what enforces, and removing it from PATH switches that check off",
    fix: fixFor([...unpinned.map(s => s.installer), ...(claudeHooks.length > 0 ? (["claude-md"] as const) : [])]),
  };
}

/** True when `path` is not a file this user can execute (the pinned node) or read (the pinned CLI). */
export function unusable(path: string, need: "exec" | "read"): boolean {
  try {
    if (!statSync(path).isFile()) return true;
    accessSync(path, need === "exec" ? constants.X_OK : constants.R_OK);
    return false;
  } catch {
    return true;
  }
}

function pinMissingCheck(scripts: InstalledScript[]): DoctorCheck {
  const missing = new Set<string>();
  const broken: InstalledScript[] = [];
  for (const s of scripts) {
    if (s.pin === null) continue;
    const gone = [
      ...(unusable(s.pin.node, "exec") ? [s.pin.node] : []),
      ...(unusable(s.pin.cli, "read") ? [s.pin.cli] : []),
    ];
    if (gone.length === 0) continue;
    broken.push(s);
    for (const p of gone) missing.add(p);
  }
  if (broken.length === 0) {
    return { code: "ENFORCEMENT_PIN_MISSING", ok: true, detail: "every pinned node and CLI path exists" };
  }
  return {
    code: "ENFORCEMENT_PIN_MISSING",
    ok: false,
    detail:
      `the pinned enforcement binary is missing or not usable (${[...missing].join(", ")}), so the ${broken.map(s => s.label).join(", ")} ` +
      "refuse(s) to run: a moved or upgraded Node or a removed install does this",
    fix: fixFor(broken.map(s => s.installer)),
  };
}

export function canonical(path: string): string {
  try {
    return realpathSync(path);
  } catch {
    return resolve(path);
  }
}

/** Every distinct (by canonical path) executable `repo-aegis` on `pathValue`, in PATH order. */
export function repoAegisOnPath(pathValue: string | undefined): Array<{ path: string; real: string }> {
  const found: Array<{ path: string; real: string }> = [];
  if (pathValue === undefined || pathValue === "") return found;
  for (const entry of pathValue.split(delimiter)) {
    const candidate = join(entry === "" ? "." : entry, "repo-aegis");
    try {
      const st = statSync(candidate);
      if (!st.isFile() || (st.mode & 0o111) === 0) continue;
    } catch {
      continue;
    }
    const real = canonical(candidate);
    if (found.some(f => f.real === real)) continue;
    found.push({ path: candidate, real });
  }
  return found;
}

/** The version in the repo-aegis package.json above `entry`, or null; never runs `entry`. */
export function versionOf(entry: string): string | null {
  let dir = dirname(entry);
  for (let i = 0; i < 4; i++) {
    const text = readText(join(dir, "package.json"));
    if (text !== null) {
      try {
        const pkg = JSON.parse(text) as { name?: unknown; version?: unknown };
        if (pkg.name === "@de-otio/repo-aegis" && typeof pkg.version === "string") return pkg.version;
      } catch {
        /* not JSON: keep walking */
      }
    }
    const up = dirname(dir);
    if (up === dir) break;
    dir = up;
  }
  return null;
}

function multipleInstallsCheck(pathValue: string | undefined, pin: EnforcementPin): DoctorCheck {
  const found = repoAegisOnPath(pathValue);
  const describe = (f: { path: string; real: string }): string => `${f.path} (${versionOf(f.real) ?? "version unknown"})`;
  const first = found[0];
  const firstIsPinned = first === undefined || first.real === canonical(pin.cli);

  if (found.length <= 1 && firstIsPinned) {
    return {
      code: "MULTIPLE_INSTALLS",
      ok: true,
      detail: found.length === 0 ? "no repo-aegis on PATH; the hooks and the shim run the pinned one" : "the only repo-aegis on PATH is the pinned one",
    };
  }
  const detail =
    found.length > 1
      ? `${found.length} repo-aegis installs are reachable on PATH: ${found.map(describe).join("; ")}. ` +
        "A person's terminal and an agent's shell can run different versions of the scanner" +
        (firstIsPinned ? "" : "; the one first on PATH is not the pinned one") +
        `; the hooks and the shim run the pinned one (${pin.cli})`
      : `the repo-aegis first on PATH (${describe(first!)}) is not the pinned one (${pin.cli}), so a person's terminal ` +
        "and the hooks and shim run different installs";
  return {
    code: "MULTIPLE_INSTALLS",
    ok: false,
    severity: "warn",
    detail,
    fix: "keep one install and remove the others, then run `repo-aegis install hooks` and `repo-aegis install shim` so the pin follows it",
  };
}

/**
 * The three pin checks for the hooks and shim under `env.REPO_AEGIS_HOME` and
 * the `repo-aegis` files reachable on `env.PATH`. `pin` is the pin THIS install
 * would write; `env` and `pin` are seams for tests.
 */
export function enforcementPinChecks(
  env: NodeJS.ProcessEnv = process.env,
  pin: EnforcementPin = currentEnforcementPin(),
  claudeHome?: string,
): DoctorCheck[] {
  const scripts = installedScripts(env["REPO_AEGIS_HOME"] ?? repoAegisHome());
  return [unpinnedCheck(scripts, unpinnedClaudeHooks(claudeHome)), pinMissingCheck(scripts), multipleInstallsCheck(env["PATH"], pin)];
}

/** A `repo-aegis` reachable on PATH and the version of its package, or null when that cannot be read. */
export interface InstallOnPath {
  path: string;
  version: string | null;
}

/** The version of the repo-aegis that is running this code, or null when its package.json cannot be found. */
export function runningInstallVersion(): string | null {
  return versionOf(fileURLToPath(import.meta.url));
}

/** `a < b` for dotted numeric versions (a prerelease suffix is ignored); unparseable parts count as 0. */
export function versionIsOlder(a: string, b: string): boolean {
  const parts = (v: string): number[] => v.split("-")[0]!.split(".").map(p => Number.parseInt(p, 10) || 0);
  const pa = parts(a);
  const pb = parts(b);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d < 0;
  }
  return false;
}

/** The CLI paths the installed git hooks and gh shim under `home` are pinned to (what they actually run). */
export function pinnedCliPaths(home: string): string[] {
  return installedScripts(home).flatMap(s => (s.pin === null ? [] : [s.pin.cli]));
}
