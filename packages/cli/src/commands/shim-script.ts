// Text of the `gh` PATH shim. This module is the SINGLE source of truth for
// the installed script; `install-shim.ts` only writes this string to disk.
// Same arrangement as `core/src/hook-scripts.ts` and for the same reason:
// a standalone `.sh` template drifts from the code that installs it, and
// the copy that drifts is the one that stops guarding.
//
// Edit here, rebuild, and run `repo-aegis install shim` again to refresh an
// installed copy.
import {
  pinAssignments,
  pinGuard,
  repoAegisHome,
  shellQuote,
  shellUnquote,
  type EnforcementPin,
} from "@de-otio/repo-aegis-core";
import type { TaaadPin } from "./taaad-pin.js";

/**
 * First comment line of the generated script. `install shim` uses it to tell
 * its own file apart from a `gh` wrapper someone else put at the same path —
 * refusing to clobber a stranger's file is the difference between an install
 * and a footgun.
 */
export const SHIM_HEADER_LINE = "# Generated by `repo-aegis install shim`";

/** What else the shim pins besides the CLI: the home the CLI reads its registry from, and taaad. */
export interface ShimPins {
  /** The repo-aegis home the CLI is told to use with `--home` (D8: it ignores `REPO_AEGIS_HOME`). Default: this process's. */
  home?: string;
  /** The taaad that mints App tokens; null or absent when none is pinned (github-app identities are then unavailable). */
  taaad?: TaaadPin | null;
}

/** `gh` arguments that bypass repo-aegis entirely (D1): they take no repository, choose no identity and publish nothing. */
export const SHIM_SKIP_WORDS: readonly string[] = ["--version", "help", "completion"];

function assertQuotable(label: string, value: string): void {
  if (value === "") throw new Error(`the pinned ${label} is empty`);
  if (/[\n\r\0]/.test(value)) throw new Error(`the pinned ${label} contains a newline or NUL character`);
}

/** The three taaad assignment lines (or a comment saying there is none). Read back by {@link parseTaaadPinFromScript}. */
function taaadAssignments(taaad: TaaadPin | null): string {
  if (taaad === null) return "# no taaad pinned: github-app identities are unavailable (re-run `repo-aegis install shim` after installing taaad)";
  for (const [label, value] of [
    ["taaad launcher", taaad.launcher],
    ["taaad interpreter", taaad.interpreter],
    ["taaad package directory", taaad.packageDir],
  ] as const) {
    assertQuotable(label, value);
  }
  return (
    `__ra_taaad=${shellQuote(taaad.launcher)}\n` +
    `__ra_taaad_interp=${shellQuote(taaad.interpreter)}\n` +
    `__ra_taaad_pkg=${shellQuote(taaad.packageDir)}`
  );
}

/** The taaad pin a shim script was rendered with; null for a script with none. */
export function parseTaaadPinFromScript(text: string): TaaadPin | null {
  const grab = (name: string): string | null => {
    const m = new RegExp(`^${name}=(.*)$`, "m").exec(text);
    return m === null ? null : shellUnquote(m[1]!);
  };
  const launcher = grab("__ra_taaad");
  const interpreter = grab("__ra_taaad_interp");
  const packageDir = grab("__ra_taaad_pkg");
  if (launcher === null || interpreter === null || packageDir === null) return null;
  return { launcher, interpreter, packageDir };
}

/** The `--home` the shim passes the CLI; null when the script has no such line. */
export function parseHomeFromScript(text: string): string | null {
  const m = /^__ra_home=(.*)$/m.exec(text);
  return m === null ? null : shellUnquote(m[1]!);
}

/**
 * The shim as `install shim` writes it for `pin`: the Node executable and CLI
 * entry it runs by absolute path instead of resolving `repo-aegis` by name
 * (doc/plan-pin-enforcement-binary.md), the home it passes with `--home`, and the taaad pin. Throws when
 * any of them cannot be quoted into a shell script (a newline or NUL in a path).
 */
export const renderShimScript = (pin: EnforcementPin, pins: ShimPins = {}): string => {
  const home = pins.home ?? repoAegisHome();
  assertQuotable("repo-aegis home", home);
  const skip = SHIM_SKIP_WORDS.join("|");
  return `\
#!/usr/bin/env bash
${SHIM_HEADER_LINE}
# Do not edit; overwritten on every \`install shim\` run. Source of truth:
# packages/cli/src/commands/shim-script.ts (renderShimScript).
#
# A PATH shim for \`gh\` (doc/design/egress-guard.md §3, doc/plan-owner-identity.md D1). Every \`gh\`
# call except \`--version\`, \`help\` and \`completion\` is handed to the pinned CLI's \`gh\` command, which
# makes the egress decision, chooses the GitHub identity, runs the real \`gh\`, and prints the receipt.
# There is NO shell code after the \`exec\`: nothing here can see a token. The CLI runs by the absolute
# path pinned at install time, never by name, so a \`repo-aegis\` or \`node\` first on PATH cannot decide
# what enforces; and with the pinned binary gone the call is REFUSED (exit 2), reads included, because
# every verb is now judged there. A person re-runs the installer.
#
# Written for bash 3.2 (macOS's stock /bin/bash): no GNU-only path
# canonicalisation flags, no bash-4 array builtins, no associative arrays —
# \`cd … && pwd -P\` does the canonicalising instead. \`set -e\` is deliberately
# NOT used.
set -u

__repo_aegis_same_file() {
  [ -e "\$1" ] && [ -e "\$2" ] || return 1
  local a b
  a="\$(cd "\$(dirname "\$1")" 2>/dev/null && pwd -P)/\$(basename "\$1")"
  b="\$(cd "\$(dirname "\$2")" 2>/dev/null && pwd -P)/\$(basename "\$2")"
  [ "\$a" = "\$b" ]
}

# --- 1. Locate the real \`gh\` ------------------------------------------------
# The first executable \`gh\` on PATH that is neither inside this shim's own
# directory nor the same file as this shim. Comparing CANONICAL paths, not
# names, is what makes self-recursion impossible even when the shim is
# reached through a symlink or a relative PATH entry. There is no hard-coded
# fallback path: a wrong guess would silently bypass the user's own \`gh\`.
__ra_self_dir="\$(cd "\$(dirname "\$0")" 2>/dev/null && pwd -P)"
__ra_self="\${__ra_self_dir}/\$(basename "\$0")"

__ra_real_gh=""
__ra_saved_ifs="\$IFS"
set -f
IFS=":"
for __ra_dir in \$PATH; do
  [ -n "\$__ra_dir" ] || __ra_dir="."
  __ra_cand="\${__ra_dir}/gh"
  [ -f "\$__ra_cand" ] && [ -x "\$__ra_cand" ] || continue
  __ra_cand_dir="\$(cd "\$__ra_dir" 2>/dev/null && pwd -P)" || continue
  [ "\$__ra_cand_dir" = "\$__ra_self_dir" ] && continue
  __repo_aegis_same_file "\$__ra_cand" "\$__ra_self" && continue
  __ra_real_gh="\$__ra_cand"
  break
done
IFS="\$__ra_saved_ifs"
set +f

if [ -z "\$__ra_real_gh" ]; then
  echo "repo-aegis shim: real gh not found on PATH" >&2
  exit 127
fi

# --- 2. The skip list ---------------------------------------------------------
# Only these take no repository and choose no identity; everything else is judged by the CLI.
case "\${1:-}" in
  ${skip}) exec "\$__ra_real_gh" "\$@" ;;
esac

# Fail CLOSED when the pinned binary is gone, exactly like the git hooks. There
# is no environment variable that skips it; a person re-runs the installer.
${pinAssignments(pin)}
__ra_home=${shellQuote(home)}
${taaadAssignments(pins.taaad ?? null)}
${pinGuard({ blocked: "shim refused a gh call", fix: "repo-aegis install shim", exitCode: 2 })}

# --- 3. Hand over -------------------------------------------------------------
# The registry and the approvals are read from the home pinned above, never from the caller's environment.
exec "\$__ra_node" "\$__ra_cli" gh --home "\$__ra_home" -- "\$@"
`;
};
